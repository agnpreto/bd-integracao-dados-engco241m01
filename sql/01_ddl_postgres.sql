-- 01_ddl_postgres.sql
-- Script DDL do banco no PostgreSQL (testei no PG 16).
-- No arquivo original tinha varios problemas (tipo float em id e preco, pk com coluna null,
-- nome de coluna errado tipo "decricao" e "idfonecedor", etc.)

DROP TABLE IF EXISTS public.venda               CASCADE;
DROP TABLE IF EXISTS public.entradas_mercadoria CASCADE;
DROP TABLE IF EXISTS public.pedido_compra       CASCADE;
DROP TABLE IF EXISTS public.produtos_filial     CASCADE;
DROP TABLE IF EXISTS public.fornecedor          CASCADE;

-- tabela de fornecedores
CREATE TABLE public.fornecedor (
    idfornecedor integer GENERATED BY DEFAULT AS IDENTITY,
    razao_social varchar(255) NOT NULL,
    CONSTRAINT fornecedor_pkey PRIMARY KEY (idfornecedor)
);

-- produtos por filial
CREATE TABLE public.produtos_filial (
    filial_id      integer        NOT NULL, -- antes podia ser null mas entrava na PK
    produto_id     varchar(25)    NOT NULL, -- tava varchar(255), deixei 25 igual nas outras
    descricao      varchar(255)   NOT NULL, -- tava escrito "decricao"
    estoque        numeric(14, 3) NOT NULL DEFAULT 0,
    preco_unitario numeric(12, 4) NOT NULL DEFAULT 0,
    preco_compra   numeric(12, 4) NOT NULL DEFAULT 0,
    preco_venda    numeric(12, 4) NOT NULL DEFAULT 0,
    idfornecedor   integer        NULL,     -- tava "idfonecedor" e sem virgula na linha de cima
    CONSTRAINT produtos_filial_pkey PRIMARY KEY (filial_id, produto_id), -- antes tava idproduto que nem existia
    CONSTRAINT produtos_filial_fornecedor_fk FOREIGN KEY (idfornecedor)
        REFERENCES public.fornecedor (idfornecedor)
);

-- pedidos de compra
CREATE TABLE public.pedido_compra (
    pedido_id         bigint         NOT NULL DEFAULT 0,
    data_pedido       date           NULL,
    item              integer        NOT NULL DEFAULT 0,
    produto_id        varchar(25)    NOT NULL DEFAULT '0',
    descricao_produto varchar(255)   NULL,
    ordem_compra      bigint         NULL, -- deixei NULL pq quando nao tem OC ainda, 0 parecia OC de verdade
    qtde_pedida       numeric(14, 3) NULL,
    filial_id         integer        NULL,
    data_entrega      date           NULL,
    qtde_entregue     numeric(14, 3) NOT NULL DEFAULT 0,
    -- nao vem na planilha, e sempre o que foi pedido menos o que ja entregou.
    -- usando GENERATED ALWAYS AS ... STORED fica calculado automatico sem risco de ficar errado
    qtde_pendente     numeric(14, 3) GENERATED ALWAYS AS (COALESCE(qtde_pedida, 0) - qtde_entregue) STORED,
    preco_compra      numeric(12, 4) NULL DEFAULT 0,
    fornecedor_id     integer        NULL, -- tirei DEFAULT 0 pq nao existe fornecedor 0
    CONSTRAINT pedido_compra_pkey PRIMARY KEY (pedido_id, produto_id, item)
);

-- entradas de mercadoria (notas)
CREATE TABLE public.entradas_mercadoria (
    data_entrada      date           NULL,
    nro_nfe           varchar(255)   NOT NULL,
    item              integer        NOT NULL DEFAULT 0,
    produto_id        varchar(25)    NOT NULL DEFAULT '0',
    descricao_produto varchar(255)   NULL,
    ordem_compra      bigint         NOT NULL, -- nao tava na tabela original mas usavam na PK, adicionei aqui
    qtde_recebida     numeric(14, 3) NULL,
    filial_id         integer        NULL,
    custo_unitario    numeric(12, 4) NOT NULL DEFAULT 0,
    CONSTRAINT entradas_mercadoria_pkey PRIMARY KEY (ordem_compra, item, produto_id, nro_nfe)
);

-- vendas
CREATE TABLE public.venda (
    venda_id       bigint         NOT NULL,
    data_emissao   date           NOT NULL,
    horariomov     time           NOT NULL DEFAULT '00:00:00', -- antes era varchar(8) e tinha cast estranho
    produto_id     varchar(25)    NOT NULL, -- tirei DEFAULT '' senao aceitava vazio
    qtde_vendida   numeric(14, 3) NULL,
    valor_unitario numeric(12, 4) NOT NULL DEFAULT 0,
    filial_id      integer        NOT NULL, -- tirei DEFAULT 1 senao escondia filial faltando
    item           integer        NOT NULL DEFAULT 0,
    unidade_medida varchar(3)     NULL,
    CONSTRAINT pk_venda PRIMARY KEY (filial_id, venda_id, data_emissao, produto_id, item, horariomov),
    CONSTRAINT venda_produto_nao_vazio CHECK (produto_id <> '')
);



-- indices pra ajudar nas consultas
CREATE INDEX idx_pedido_compra_ordem ON public.pedido_compra (ordem_compra);
CREATE INDEX idx_venda_data          ON public.venda (data_emissao);